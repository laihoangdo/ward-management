#!/usr/bin/env node
/**
 * One-off import of the OpenStreetMap road network around Bà Điểm for on-device routing on the 3D field map.
 *
 * Only the bounding box of the commune boundary (plus a margin) is sent to the Overpass API; no project or household data
 * leaves the machine. The result is written as a Liquibase SQL file so servers load the roads without network access.
 * Data © OpenStreetMap contributors, ODbL 1.0 (attribution is shown on the map).
 *
 *   node scripts/osm/import-badiem-roads.mjs [--from saved-overpass.json]
 */
import { readFileSync, writeFileSync } from 'node:fs';

const BOUNDARIES = 'src/main/webapp/content/data/badiem-hamlet-boundaries.geojson';
const OUTPUT = 'src/main/resources/config/liquibase/sql/badiem_roads_osm.sql';
const OVERPASS = 'https://overpass-api.de/api/interpreter';
const MARGIN_M = 300;

// Highways a motorbike or a person on foot can use; construction/proposed/platform and similar are left out.
const DRIVABLE = new Set([
  'motorway',
  'motorway_link',
  'trunk',
  'trunk_link',
  'primary',
  'primary_link',
  'secondary',
  'secondary_link',
  'tertiary',
  'tertiary_link',
  'unclassified',
  'residential',
  'living_street',
  'service',
  'track',
  'road',
]);
const FOOT_ONLY = new Set(['path', 'footway', 'pedestrian', 'steps', 'cycleway']);
const NO = new Set(['no', 'private_no']);

function bbox() {
  const data = JSON.parse(readFileSync(BOUNDARIES, 'utf8'));
  let [w, s, e, n] = [180, 90, -180, -90];
  const walk = c => {
    if (typeof c[0] === 'number') {
      w = Math.min(w, c[0]);
      s = Math.min(s, c[1]);
      e = Math.max(e, c[0]);
      n = Math.max(n, c[1]);
    } else c.forEach(walk);
  };
  data.features.forEach(f => walk(f.geometry.coordinates));
  const dLat = MARGIN_M / 111_320;
  const dLng = MARGIN_M / (111_320 * Math.cos((((s + n) / 2) * Math.PI) / 180));
  return [s - dLat, w - dLng, n + dLat, e + dLng].map(v => +v.toFixed(6));
}

async function download() {
  const [s, w, n, e] = bbox();
  const query = `[out:json][timeout:180];way["highway"](${s},${w},${n},${e});out tags geom;`;
  const response = await fetch(OVERPASS, {
    method: 'POST',
    headers: { 'Content-Type': 'application/x-www-form-urlencoded', 'User-Agent': 'field-map-road-import/1.0' },
    body: `data=${encodeURIComponent(query)}`,
  });
  if (!response.ok) throw new Error(`Overpass HTTP ${response.status}: ${(await response.text()).slice(0, 300)}`);
  return response.json();
}

const quote = v => (v == null ? 'NULL' : `'${String(v).replace(/;/g, ',').replace(/'/g, "''")}'`);

function road(way) {
  const t = way.tags ?? {};
  const type = t.highway;
  if (!DRIVABLE.has(type) && !FOOT_ONLY.has(type)) return null;
  if (t.area === 'yes') return null;
  const points = [];
  for (const p of way.geometry ?? []) {
    const point = [+p.lon.toFixed(7), +p.lat.toFixed(7)];
    const last = points[points.length - 1];
    if (!last || last[0] !== point[0] || last[1] !== point[1]) points.push(point);
  }
  if (points.length < 2) return null;
  const vehicleBanned = [t.access, t.vehicle, t.motor_vehicle, t.motorcycle].some(v => NO.has(v)) && t.motorcycle !== 'yes';
  const oneway = t.oneway === '-1' ? '-1' : ['yes', '1', 'true'].includes(t.oneway) || t.junction === 'roundabout' ? 'yes' : 'no';
  return {
    id: `osm:way/${way.id}`,
    name: t.name ?? t['name:vi'] ?? t.ref ?? null,
    type,
    oneway,
    motorcycle: DRIVABLE.has(type) && !vehicleBanned,
    foot: !['motorway', 'motorway_link'].includes(type) && t.foot !== 'no' && t.access !== 'no',
    geometry: JSON.stringify({ type: 'LineString', coordinates: points }),
  };
}

const fromIndex = process.argv.indexOf('--from');
const data = fromIndex > 0 ? JSON.parse(readFileSync(process.argv[fromIndex + 1], 'utf8')) : await download();
const roads = data.elements
  .filter(e => e.type === 'way')
  .map(road)
  .filter(Boolean)
  .sort((a, b) => a.id.localeCompare(b.id));

const lines = [
  '-- Generated by scripts/osm/import-badiem-roads.mjs. Do not edit by hand; re-run the script to refresh.',
  `-- Data © OpenStreetMap contributors, ODbL 1.0. Downloaded ${new Date().toISOString().slice(0, 10)}; ${roads.length} ways.`,
];
for (let i = 0; i < roads.length; i += 200) {
  const values = roads
    .slice(i, i + 200)
    .map(
      r =>
        `(${quote(r.id)},${quote(r.name)},${quote(r.type)},'ACTIVE',${quote(r.geometry)},${quote(r.oneway)},${r.motorcycle},${r.foot},'OSM')`,
    );
  lines.push(
    'INSERT INTO public.gis_road(external_id,name,road_type,status,geometry_geojson,oneway,motorcycle_allowed,foot_allowed,source) VALUES',
    values.join(',\n'),
    'ON CONFLICT (external_id) DO UPDATE SET name=EXCLUDED.name,road_type=EXCLUDED.road_type,geometry_geojson=EXCLUDED.geometry_geojson,' +
      'oneway=EXCLUDED.oneway,motorcycle_allowed=EXCLUDED.motorcycle_allowed,foot_allowed=EXCLUDED.foot_allowed,source=EXCLUDED.source;',
  );
}
writeFileSync(OUTPUT, `${lines.join('\n')}\n`);
const km = roads.reduce((sum, r) => {
  const c = JSON.parse(r.geometry).coordinates;
  for (let i = 1; i < c.length; i++) {
    const dy = (c[i][1] - c[i - 1][1]) * 111_320;
    const dx = (c[i][0] - c[i - 1][0]) * 111_320 * Math.cos((c[i][1] * Math.PI) / 180);
    sum += Math.hypot(dx, dy) / 1000;
  }
  return sum;
}, 0);
console.log(`${roads.length} roads (${km.toFixed(0)} km; motorbike ${roads.filter(r => r.motorcycle).length}) -> ${OUTPUT}`);
