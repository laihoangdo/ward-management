package com.policemanagement.com.service.gis;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;

import com.policemanagement.com.service.rbac.RbacService;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Map;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.ObjectMapper;

/** The OpenStreetMap road import loads as valid WGS84 lines and is served as GeoJSON with a change-sensitive tag. */
@EnabledIfEnvironmentVariable(named = "RUN_TC2_DB_TESTS", matches = "true")
class GisRoadPostgresTest {

    JdbcTemplate db;
    GisRoadService service;

    @BeforeEach
    void setup() throws Exception {
        db = new JdbcTemplate(new DriverManagerDataSource("jdbc:postgresql://localhost:5432/tc2_roster_validation", "Monolithic", ""));
        assertEquals("tc2_roster_validation", db.queryForObject("select current_database()", String.class));
        db.execute("drop table if exists public.gis_road cascade");
        // Table as created by the 3D model changelog; the road changelog adds travel rules and loads the import.
        db.execute(
            "create table public.gis_road(id bigint generated by default as identity primary key,map_id bigint,external_id varchar(120)," +
                "name varchar(255),road_type varchar(32) not null,width_m double precision,status varchar(40),geometry_geojson text not null)"
        );
        String xml = Files.readString(Path.of("src/main/resources/config/liquibase/changelog/20261116000000_gis_road_osm.xml"));
        String alter = xml.substring(xml.indexOf("<sql>") + 5, xml.indexOf("</sql>"));
        db.execute(alter);
        db.execute(Files.readString(Path.of("src/main/resources/config/liquibase/sql/badiem_roads_osm.sql")));
        RbacService rbac = mock(RbacService.class);
        when(rbac.current()).thenReturn(Map.of());
        service = new GisRoadService(db, rbac);
    }

    @Test
    void importedRoadsAreValidLinesWithTravelRulesAndServedAsGeoJson() throws Exception {
        long count = db.queryForObject("select count(*) from public.gis_road where source='OSM'", Long.class);
        assertTrue(count > 5000, "OSM import too small: " + count);
        assertTrue(db.queryForObject("select count(*) from public.gis_road where oneway<>'no'", Long.class) > 0);
        assertTrue(db.queryForObject("select count(*) from public.gis_road where not motorcycle_allowed", Long.class) > 0);
        // Re-running the import updates rows in place.
        db.execute(Files.readString(Path.of("src/main/resources/config/liquibase/sql/badiem_roads_osm.sql")));
        assertEquals(count, db.queryForObject("select count(*) from public.gis_road", Long.class));

        var first = service.roads();
        JsonNode json = new ObjectMapper().readTree(first.geojson());
        assertEquals("\"FeatureCollection\"", json.get("type").toString());
        assertEquals(count, json.get("features").size());
        JsonNode feature = json.get("features").get(0);
        assertEquals("\"LineString\"", feature.get("geometry").get("type").toString());
        assertTrue(feature.get("properties").has("oneway"));
        // Every road is a WGS84 line of at least two distinct points inside the BÃ  Äiá»ƒm area (PostGIS re-checks on load).
        for (JsonNode road : json.get("features")) {
            JsonNode points = road.get("geometry").get("coordinates");
            assertEquals("\"LineString\"", road.get("geometry").get("type").toString());
            assertTrue(points.size() >= 2);
            assertNotEquals(points.get(0).toString(), points.get(1).toString());
            for (JsonNode point : points) {
                assertTrue(point.get(0).doubleValue() > 106.49 && point.get(0).doubleValue() < 106.66, point.toString());
                assertTrue(point.get(1).doubleValue() > 10.78 && point.get(1).doubleValue() < 10.92, point.toString());
            }
        }
        assertTrue(feature.get("properties").has("motorcycle"));
        assertSame(first, service.roads());

        db.update("update public.gis_road set oneway='yes' where id=(select min(id) from public.gis_road where oneway='no')");
        assertNotEquals(first.etag(), service.roads().etag());
        db.update("update public.gis_road set status='REMOVED' where id=(select min(id) from public.gis_road)");
        assertEquals(count - 1, new ObjectMapper().readTree(service.roads().geojson()).get("features").size());
    }
}
